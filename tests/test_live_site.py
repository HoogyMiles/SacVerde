HOOGY = sql("select id from teams where name='Roaring Hoogy'")
# give every Roaring Hoogy week-8 starter a stat line: 10 rushing+receiving yards each (1.00 pt), QB 250 pass yd + 2 TD (18.00)
sql(f"""insert into player_week_stats (season, week, player_id, stats, points)
  select 2026, 8, l.player_id, s.stats, score_stats(s.stats, p.pos)
    from lineups l join players p on p.id = l.player_id,
         lateral (select case p.pos when 'QB' then '{{"pass_yd":250,"pass_td":2}}'::jsonb when 'DST' then '{{"yds_allow":250}}'::jsonb
                                    when 'K' then '{{"xpm":2}}'::jsonb else '{{"rush_yd":10}}'::jsonb end stats) s
   where l.season = 2026 and l.week = 8 and l.team_id = {HOOGY}""")
expected = float(sql(f"select points from team_week_points where season=2026 and week=8 and team_id={HOOGY}"))
