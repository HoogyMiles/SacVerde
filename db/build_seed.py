"""Builds db/003_seed.sql from NFL Salary List Primary.xlsx + the 2025 data in the old site file."""
import json, re, openpyxl

NFL = {
 'Arizona Cardinals':'ARI','Atlanta Falcons':'ATL','Baltimore Ravens':'BAL','Buffalo Bills':'BUF',
 'Carolina Panthers':'CAR','Chicago Bears':'CHI','Cincinnati Bengals':'CIN','Cleveland Browns':'CLE',
 'Dallas Cowboys':'DAL','Denver Broncos':'DEN','Detroit Lions':'DET','Green Bay Packers':'GB',
 'Houston Texans':'HOU','Indianapolis Colts':'IND','Jacksonville Jaguars':'JAX','Kansas City Chiefs':'KC',
 'Las Vegas Raiders':'LV','Los Angeles Chargers':'LAC','Los Angeles Rams':'LAR','Miami Dolphins':'MIA',
 'Minnesota Vikings':'MIN','New England Patriots':'NE','New Orleans Saints':'NO','New York Giants':'NYG',
 'New York Jets':'NYJ','Philadelphia Eagles':'PHI','Pittsburgh Steelers':'PIT','San Francisco 49ers':'SF',
 'Seattle Seahawks':'SEA','Tampa Bay Buccaneers':'TB','Tennessee Titans':'TEN','Washington Commanders':'WAS',
 'FA':'FA'}
NAME_OF = {v:k for k,v in NFL.items()}; NAME_OF['FA'] = 'Free Agent'

# Duplicate rows found in the 2026 Salary List (same player listed on two NFL teams).
# Keep ONE row per player: the ranked row; if both ranked, the one with more sources.
# Flagged for Hoogs to confirm current NFL teams.
def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

wb = openpyxl.load_workbook('NFL Salary List Primary.xlsx', read_only=True, data_only=True)
sl = list(wb['2026 Salary List'].iter_rows(values_only=True))[1:]
ro = list(wb['Rosters'].iter_rows(values_only=True))[1:]
bio = {(r[1], r[3], r[0]): r for r in ro}

best = {}
dupes = []
for r in sl:
    team, name, pos, rk, avg, srcs, fin, sal = r
    key = (name, pos)
    if key in best:
        dupes.append(key)
        o = best[key]
        if (srcs or 0) > (o[5] or 0): best[key] = r
    else:
        best[key] = r

out = ["-- =====================================================================",
       "-- SacVerde League — 003: seed data (generated by build_seed.py)",
       "-- Run AFTER 002_security.sql",
       "-- =====================================================================",
       "begin;",
       "insert into public.seasons (year, is_current, current_week) values (2025, false, 17), (2026, true, 8);",
       "insert into public.nfl_teams (abbr, name) values " +
       ", ".join(f"({q(a)}, {q(NAME_OF[a])})" for a in sorted(NAME_OF)) + ";"]

D = json.load(open('data2025.json'))
divs = sorted({t['info']['division'].title() for t in D['teams'].values()})
out.append("insert into public.divisions (name) values " + ", ".join(f"({q(d)})" for d in divs) + ";")
for tname, t in D['teams'].items():
    out.append(f"insert into public.teams (name, division_id) select {q(tname)}, id from public.divisions where name = {q(t['info']['division'].title())};")

# Logins — emails from the 2025 league sheet. Roaring Hoogy = commissioner for the build.
for tname, t in D['teams'].items():
    e = (t['info'].get('email') or '').strip().lower()
    if not e: continue
    role = 'commissioner' if tname == 'Roaring Hoogy' else 'manager'
    out.append(f"insert into public.league_members (email, team_id, phone, role) select {q(e)}, id, {q(t['info'].get('phone'))}, {q(role)} from public.teams where name = {q(tname)};")

# Players + 2026 salaries
rows = []
for (name, pos), r in best.items():
    team = NFL[r[0]]
    b = bio.get((name, pos, r[0]))
    rookie = r[3] in ('R', 'Y') or (b is not None and str(b[6]) == 'R')
    jersey = b[2] if b and isinstance(b[2], int) else None
    rows.append((name, pos, team, jersey, b[4] if b else None, b[5] if b and isinstance(b[5], int) else None,
                 str(b[6]) if b and b[6] is not None else None, b[7] if b else None, rookie,
                 int(r[7]), r[4], r[6], r[5]))
for i in range(0, len(rows), 200):
    chunk = rows[i:i+200]
    out.append("with v(name,pos,nfl,jersey,height,weight,exp,college,rookie,sal,avg,fin,src) as (values " +
               ",\n ".join("(" + ",".join(q(x) for x in row[:8]) + f",{q(row[8])},{row[9]},{q(row[10])}::numeric,{q(row[11])}::int,{q(row[12])}::int)" for row in chunk) +
               "),\n ins as (insert into public.players (name,pos,nfl_team,jersey,height,weight,experience,college,rookie) "
               "select name,pos,nfl,jersey,height,weight,exp,college,rookie from v returning id,name,pos)\n"
               "insert into public.player_salaries (season,player_id,list_salary,avg_pos_rank,pos_finish,sources_used) "
               "select 2026, ins.id, v.sal, v.avg, v.fin, v.src from ins join v on v.name=ins.name and v.pos=ins.pos;")

# 2025 archive: matchups
def clean(n): return re.sub(r'^[a-z] - ', '', n)
for wk, games in D['weeks'].items():
    for g in games:
        out.append(f"insert into public.matchups (season, week, home_team, away_team, home_pts, away_pts) "
                   f"select 2025, {int(wk)}, h.id, a.id, {g['hs']}, {g['as']} from public.teams h, public.teams a "
                   f"where h.name = {q(clean(g['home']))} and a.name = {q(clean(g['away']))};")
# 2025 team pages (no contact info), draft, financials
for tname, t in D['teams'].items():
    page = {k: v for k, v in t.items() if k != 'info'}
    page['info'] = {k: v for k, v in t['info'].items() if k not in ('phone', 'email')}
    out.append(f"insert into public.season_archive (season, kind, key, data) values (2025, 'team_page', {q(tname)}, {q(json.dumps(page))}::jsonb);")
out.append(f"insert into public.season_archive (season, kind, key, data) values (2025, 'divisions', '', {q(json.dumps(D['divisions']))}::jsonb);")
out.append(f"insert into public.season_archive (season, kind, key, data) values (2025, 'draft', '', {q(json.dumps(json.load(open('draft2025.json'))['2025']))}::jsonb);")
out.append(f"insert into public.season_archive (season, kind, key, data) values (2025, 'salary_list', '', {q(json.dumps(D['salary_list']))}::jsonb);")
out.append("commit;")
open('db/003_seed.sql', 'w', encoding='utf-8').write("\n".join(out) + "\n")
print("players:", len(rows), "| duplicate rows collapsed:", sorted(set(dupes)))
